-- Initial schema, matching the JPA entities (City, Venue, Event)
CREATE EXTENSION IF NOT EXISTS postgis;

CREATE TABLE city (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name              VARCHAR(255) NOT NULL,
    country           VARCHAR(255) NOT NULL,
    latitude          DOUBLE PRECISION,
    longitude         DOUBLE PRECISION,
    events_updated_on DATE
);
CREATE INDEX city_name_lower_idx ON city (lower(name));

CREATE TABLE venue (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(255) NOT NULL,
    description   VARCHAR(2000),
    type          VARCHAR(50)  NOT NULL,
    city_id       BIGINT       NOT NULL REFERENCES city (id),
    -- embedded Address
    street        VARCHAR(255),
    house_number  VARCHAR(50),
    postal_code   VARCHAR(50),
    latitude      DOUBLE PRECISION,
    longitude     DOUBLE PRECISION,
    osm_id        BIGINT UNIQUE,
    opening_hours VARCHAR(1000),
    image_url     VARCHAR(2048),
    wikidata      VARCHAR(50),
    -- Filled in by Postgres from latitude/longitude, so the Java code never has to touch it.
    -- Note: ST_MakePoint takes longitude first.
    location      GEOGRAPHY(Point, 4326) GENERATED ALWAYS AS (
                      ST_SetSRID(ST_MakePoint(longitude, latitude), 4326)::geography
                  ) STORED
);
CREATE INDEX venue_city_idx     ON venue (city_id);
CREATE INDEX venue_location_idx ON venue USING GIST (location);

CREATE TABLE event (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(500)  NOT NULL,
    description VARCHAR(2000),
    start_time  TIMESTAMP(6)  NOT NULL,
    end_time    TIMESTAMP(6),
    entry_price NUMERIC(38, 2),
    venue_id    BIGINT        NOT NULL REFERENCES venue (id),
    external_id VARCHAR(255) UNIQUE,
    url         VARCHAR(2048),
    image_url   VARCHAR(2048),
    category    VARCHAR(255),
    genre       VARCHAR(255)
);
CREATE INDEX event_venue_idx      ON event (venue_id);
CREATE INDEX event_start_time_idx ON event (start_time);
