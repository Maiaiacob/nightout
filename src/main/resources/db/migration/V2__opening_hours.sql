-- Opening hours as weekly time slots, so the database can answer "which bars are open right now?"
--
-- One row per opening slot. Times are minutes after midnight of day_of_week (1 = Monday ... 7 = Sunday).
-- A bar that closes after midnight keeps the slot on the day it opened, with closes_minute past 1440:
-- Friday 22:00-03:00 is stored as (5, 1320, 1620).

-- NULL = not processed yet, TRUE = hours understood, FALSE = no hours or hours we can't read
ALTER TABLE venue ADD COLUMN hours_parsed BOOLEAN;

CREATE TABLE venue_opening_period (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    venue_id      BIGINT   NOT NULL REFERENCES venue (id) ON DELETE CASCADE,
    day_of_week   SMALLINT NOT NULL CHECK (day_of_week BETWEEN 1 AND 7),
    opens_minute  INTEGER  NOT NULL CHECK (opens_minute BETWEEN 0 AND 1440),
    closes_minute INTEGER  NOT NULL CHECK (closes_minute > opens_minute AND closes_minute <= 2880)
);
CREATE INDEX venue_opening_period_venue_day_idx ON venue_opening_period (venue_id, day_of_week);
